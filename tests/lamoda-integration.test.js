import test from 'node:test';
import assert from 'node:assert/strict';
import {Tracker} from '../src/service.js';
import {LamodaService} from '../src/providers/lamoda/service.js';
import {makeServer,listen} from '../src/web.js';
import {Authentication,createCredentials} from '../src/auth.js';
import {TelegramBot,TelegramError} from '../src/telegram.js';
import {temporary,cleanup} from './helpers.js';

const item = {sku:'SYNTHETIC001',title:'Пример Куртка',color:'синий',url:'https://www.lamoda.ru/p/synthetic001/clothes-example/',image_url:null,price:100000,original_price:120000,availability:'available'};
const channel = () => ({available:() => true,request:async () => ({account_id:'42',items:[item]})});
test('Lamoda HTTP API protects account operations, rejects card refreshes, and isolates schedules and data',async t => {
  const root = temporary(t),tracker = new Tracker(root),lamoda = new LamodaService(root,{channel,logger:() => {}});
  lamoda.db.bindAccount('42');
  const auth = new Authentication(await createCredentials('test-owner','synthetic-login-password'));
  const server = makeServer(tracker,{lamoda,auth}),port = await listen(server,0),base = 'http://127.0.0.1:'+port;
  cleanup(t,async () => {server.closeAllConnections();await new Promise(resolve => server.close(resolve));await lamoda.close();await tracker.close();});
  assert.equal((await fetch(base+'/lamoda')).status,200);assert.equal((await fetch(base+'/lamoda/login')).status,200);
  assert.equal((await fetch(base+'/api/providers/lamoda/dashboard')).status,401);
  const anon = await (await fetch(base+'/api/auth')).json();
  const response = await fetch(base+'/api/login',{method:'POST',headers:{'Content-Type':'application/json','X-CSRF-Token':anon.csrf_token},body:JSON.stringify({login:'test-owner',password:'synthetic-login-password'})});
  const state = await response.json(),cookie = response.headers.get('set-cookie').split(';')[0];
  const post = (path,data = {},extra = {}) => fetch(base+'/api/providers/lamoda/'+path,{method:'POST',headers:{Cookie:cookie,'Content-Type':'application/json','X-CSRF-Token':state.csrf_token,...extra},body:JSON.stringify(data)});
  assert.equal((await post('login/start',{}, {'X-CSRF-Token':'wrong'})).status,403);
  assert.equal((await post('login/start',{}, {Origin:'https://other.test'})).status,403);
  assert.equal((await post('refresh',{id:'lamoda:item:SYNTHETIC001'})).status,400);
  const previousSchedule = JSON.stringify(tracker.status().schedule);
  assert.equal((await post('settings',{schedule_enabled:true,schedule_mode:'hours',schedule:['24:00','00:00','12:00']})).status,200);
  assert.deepEqual(lamoda.status().schedule,['00:00','12:00']);assert.equal(JSON.stringify(tracker.status().schedule),previousSchedule);
  assert.equal((await post('refresh')).status,202);await lamoda.running;
  const dashboard = await (await fetch(base+'/api/providers/lamoda/dashboard',{headers:{Cookie:cookie}})).json();
  assert.equal(dashboard.items[0].price,100000);assert.equal(tracker.db.rows('favorites').length,0);
  assert.doesNotMatch(JSON.stringify(dashboard),/account_id|account_digest|session\.json/);
  const history = await fetch(base+'/api/providers/lamoda/product/lamoda%3Aitem%3ASYNTHETIC001/history?days=0',{headers:{Cookie:cookie}});
  assert.equal(history.status,200);assert.equal((await history.json()).points.length,1);
});
test('Lamoda Telegram queue survives transport failure and never creates its tables in Randewoo',async t => {
  const root = temporary(t),tracker = new Tracker(root),lamoda = new LamodaService(root,{channel,logger:() => {}});
  const calls = [],api = {fail:true,close(){},async call(method,data) {if (this.fail) throw new TelegramError('transport');calls.push({method,data});return {message_id:123};}};
  const bot = new TelegramBot(tracker,{api,ownerId:123,lamoda,publicOrigin:'https://prices.example',logger:() => {}});
  cleanup(t,async () => {await bot.close();await lamoda.close();await tracker.close();});
  lamoda.db.bindAccount('42');await lamoda.start();await lamoda.running;
  await bot.flush();const pending = lamoda.db.db.prepare('SELECT * FROM telegram_outbox').get();assert.equal(pending.attempts,1);assert.equal(pending.delivered_at,null);
  assert.equal(tracker.db.get("SELECT COUNT(*) AS n FROM sqlite_master WHERE name LIKE '%lamoda%'").n,0);
  lamoda.db.db.prepare('UPDATE telegram_outbox SET next_attempt_ms=0').run();api.fail = false;await bot.flush();await bot.flush();
  assert.equal(calls.length,1);assert.match(calls[0].data.text,/Lamoda/);assert.match(calls[0].data.text,/Следующая проверка/);
  assert.equal(calls[0].data.reply_markup.inline_keyboard[0][0].url,'https://prices.example/lamoda');
  assert.equal(lamoda.db.db.prepare('SELECT message_id FROM telegram_outbox').get().message_id,123);
});
